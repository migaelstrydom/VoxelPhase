//! Marching Cubes algorithm for generating smooth meshes from voxel data.
//!
//! This implementation converts a 3D grid of density values into triangles,
//! creating smooth surfaces at the boundary between solid and empty voxels.

use nalgebra::{Point3, Vector3};

use super::voxel::Voxel;

/// Result of marching cubes mesh generation.
pub struct MarchingCubesMesh {
    /// Vertex positions.
    pub positions: Vec<Point3<f32>>,
    /// Vertex normals.
    pub normals: Vec<Vector3<f32>>,
    /// Vertex colors (from material).
    pub colors: Vec<[f32; 4]>,
    /// Triangle indices.
    pub indices: Vec<u32>,
}

impl MarchingCubesMesh {
    /// Create an empty mesh.
    pub fn new() -> Self {
        Self {
            positions: Vec::new(),
            normals: Vec::new(),
            colors: Vec::new(),
            indices: Vec::new(),
        }
    }
}

impl Default for MarchingCubesMesh {
    fn default() -> Self {
        Self::new()
    }
}

/// Marching Cubes mesh generator.
pub struct MarchingCubes {
    /// Threshold for surface (typically 0.0 for signed distance).
    pub iso_level: f32,
}

impl MarchingCubes {
    pub fn new() -> Self {
        Self { iso_level: 0.0 }
    }

    /// Generate mesh for a sub-range of cells within a sample grid.
    ///
    /// The grid is indexed as `grid[x][y][z]`, and the world position of
    /// `grid[x][y][z]` is `lattice_origin + (first_sample + (x, y, z)) * cell_size`.
    /// Expressing positions as a multiple of the *global* sample index — rather
    /// than as an offset from a per-block origin — makes vertex positions
    /// bit-identical between blocks that share a sample plane, so meshes from
    /// neighbouring chunks join without a seam.
    ///
    /// Only cells with index in `cell_lo[a] .. cell_hi[a]` (per axis) are
    /// emitted; the remaining samples still participate as gradient neighbours,
    /// which keeps normals continuous across a block boundary.
    pub fn generate_range(
        &self,
        grid: &[Vec<Vec<Voxel>>],
        lattice_origin: Point3<f32>,
        first_sample: [i32; 3],
        cell_size: f32,
        cell_lo: [usize; 3],
        cell_hi: [usize; 3],
    ) -> MarchingCubesMesh {
        let mut mesh = MarchingCubesMesh::new();

        let size_x = grid.len();
        if size_x < 2 {
            return mesh;
        }
        let size_y = grid[0].len();
        if size_y < 2 {
            return mesh;
        }
        let size_z = grid[0][0].len();
        if size_z < 2 {
            return mesh;
        }

        let hi = [
            cell_hi[0].min(size_x - 1),
            cell_hi[1].min(size_y - 1),
            cell_hi[2].min(size_z - 1),
        ];

        for x in cell_lo[0]..hi[0] {
            for y in cell_lo[1]..hi[1] {
                for z in cell_lo[2]..hi[2] {
                    self.process_cell(
                        grid,
                        x,
                        y,
                        z,
                        lattice_origin,
                        first_sample,
                        cell_size,
                        &mut mesh,
                    );
                }
            }
        }

        mesh
    }

    #[allow(clippy::too_many_arguments)]
    fn process_cell(
        &self,
        grid: &[Vec<Vec<Voxel>>],
        x: usize,
        y: usize,
        z: usize,
        lattice_origin: Point3<f32>,
        first_sample: [i32; 3],
        cell_size: f32,
        mesh: &mut MarchingCubesMesh,
    ) {
        // World position of a sample, expressed from its global lattice index.
        let sample_pos = |ix: usize, iy: usize, iz: usize| {
            Point3::new(
                lattice_origin.x + (first_sample[0] + ix as i32) as f32 * cell_size,
                lattice_origin.y + (first_sample[1] + iy as i32) as f32 * cell_size,
                lattice_origin.z + (first_sample[2] + iz as i32) as f32 * cell_size,
            )
        };
        // Get the 8 corner voxels of this cell
        let corners = [
            &grid[x][y][z],
            &grid[x + 1][y][z],
            &grid[x + 1][y][z + 1],
            &grid[x][y][z + 1],
            &grid[x][y + 1][z],
            &grid[x + 1][y + 1][z],
            &grid[x + 1][y + 1][z + 1],
            &grid[x][y + 1][z + 1],
        ];

        // Compute corner positions
        let positions = [
            sample_pos(x, y, z),
            sample_pos(x + 1, y, z),
            sample_pos(x + 1, y, z + 1),
            sample_pos(x, y, z + 1),
            sample_pos(x, y + 1, z),
            sample_pos(x + 1, y + 1, z),
            sample_pos(x + 1, y + 1, z + 1),
            sample_pos(x, y + 1, z + 1),
        ];

        // Compute cube index based on which corners are inside the surface
        let mut cube_index = 0u8;
        for (i, corner) in corners.iter().enumerate() {
            if corner.density > self.iso_level {
                cube_index |= 1 << i;
            }
        }

        // Skip if entirely inside or outside
        if cube_index == 0 || cube_index == 255 {
            return;
        }

        // Get edge flags from table
        let edge_flags = EDGE_TABLE[cube_index as usize];
        if edge_flags == 0 {
            return;
        }

        // Gradient of the density field at each corner, via central differences
        // on the grid (clamped at boundaries). The surface normal is the
        // negated, normalised gradient since density > 0 marks the interior.
        let corner_indices = [
            (x, y, z),
            (x + 1, y, z),
            (x + 1, y, z + 1),
            (x, y, z + 1),
            (x, y + 1, z),
            (x + 1, y + 1, z),
            (x + 1, y + 1, z + 1),
            (x, y + 1, z + 1),
        ];
        let mut corner_gradients = [Vector3::zeros(); 8];
        for (i, (cx, cy, cz)) in corner_indices.iter().enumerate() {
            corner_gradients[i] = sample_gradient(grid, *cx, *cy, *cz, cell_size);
        }

        // Interpolate vertices, colors, and normals on edges
        let mut edge_vertices = [Point3::origin(); 12];
        let mut edge_colors = [[0.0f32; 4]; 12];
        let mut edge_normals = [Vector3::zeros(); 12];

        for i in 0..12 {
            if edge_flags & (1 << i) != 0 {
                let (v0, v1) = EDGE_CONNECTIONS[i];
                let d0 = corners[v0].density;
                let d1 = corners[v1].density;
                let t = lerp_t(d0, d1, self.iso_level);
                edge_vertices[i] =
                    Point3::from(positions[v0].coords.lerp(&positions[v1].coords, t));
                // Colour comes from the solid side only. Blending toward the
                // air corner pulls the vertex colour toward transparent black,
                // which darkens exposed surfaces where t is close to 0 or 1
                // (e.g. destroyed voxels or grid-aligned heightfields).
                let solid_corner = if d0 > self.iso_level { v0 } else { v1 };
                edge_colors[i] = corners[solid_corner].material.color();
                let grad = corner_gradients[v0].lerp(&corner_gradients[v1], t);
                let n = -grad;
                edge_normals[i] = if n.magnitude_squared() > 1e-10 {
                    n.normalize()
                } else {
                    Vector3::new(0.0, 1.0, 0.0)
                };
            }
        }

        // Get triangles from table
        let triangles = &TRI_TABLE[cube_index as usize];
        let base_index = mesh.positions.len() as u32;

        let mut i = 0;
        while i < triangles.len() && triangles[i] != -1 {
            // Add three vertices for this triangle
            for j in 0..3 {
                let edge = triangles[i + j] as usize;
                mesh.positions.push(edge_vertices[edge]);
                mesh.colors.push(edge_colors[edge]);
                mesh.normals.push(edge_normals[edge]);
                mesh.indices.push(base_index + (i + j) as u32);
            }
            i += 3;
        }
    }
}

/// Central-difference gradient of the density field at grid index (x,y,z).
/// Falls back to forward/backward differences at the grid boundary.
fn sample_gradient(
    grid: &[Vec<Vec<Voxel>>],
    x: usize,
    y: usize,
    z: usize,
    cell_size: f32,
) -> Vector3<f32> {
    let size_x = grid.len();
    let size_y = grid[0].len();
    let size_z = grid[0][0].len();

    let d = |cx: usize, cy: usize, cz: usize| grid[cx][cy][cz].density;

    let dx = if x == 0 {
        (d(x + 1, y, z) - d(x, y, z)) / cell_size
    } else if x + 1 >= size_x {
        (d(x, y, z) - d(x - 1, y, z)) / cell_size
    } else {
        (d(x + 1, y, z) - d(x - 1, y, z)) / (2.0 * cell_size)
    };

    let dy = if y == 0 {
        (d(x, y + 1, z) - d(x, y, z)) / cell_size
    } else if y + 1 >= size_y {
        (d(x, y, z) - d(x, y - 1, z)) / cell_size
    } else {
        (d(x, y + 1, z) - d(x, y - 1, z)) / (2.0 * cell_size)
    };

    let dz = if z == 0 {
        (d(x, y, z + 1) - d(x, y, z)) / cell_size
    } else if z + 1 >= size_z {
        (d(x, y, z) - d(x, y, z - 1)) / cell_size
    } else {
        (d(x, y, z + 1) - d(x, y, z - 1)) / (2.0 * cell_size)
    };

    Vector3::new(dx, dy, dz)
}

/// Interpolation parameter for an MC edge crossing the iso-surface.
fn lerp_t(d0: f32, d1: f32, iso_level: f32) -> f32 {
    let t = if (d1 - d0).abs() > 1e-6 {
        (iso_level - d0) / (d1 - d0)
    } else {
        0.5
    };
    t.clamp(0.0, 1.0)
}

