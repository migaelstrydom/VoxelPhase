//! Marching Cubes algorithm for generating smooth meshes from voxel data.
//!
//! This implementation converts a 3D grid of density values into triangles,
//! creating smooth surfaces at the boundary between solid and empty voxels.

use nalgebra::{Point3, Vector3};

use super::voxel::Voxel;

/// Result of marching cubes mesh generation.
pub struct MarchingCubesMesh {
    /// Vertex positions.
    pub positions: Vec<Point3<f32>>,
    /// Vertex normals.
    pub normals: Vec<Vector3<f32>>,
    /// Vertex colors (from material).
    pub colors: Vec<[f32; 4]>,
    /// Triangle indices.
    pub indices: Vec<u32>,
}

impl MarchingCubesMesh {
    /// Create an empty mesh.
    pub fn new() -> Self {
        Self {
            positions: Vec::new(),
            normals: Vec::new(),
            colors: Vec::new(),
            indices: Vec::new(),
        }
    }
}

impl Default for MarchingCubesMesh {
    fn default() -> Self {
        Self::new()
    }
}

/// Marching Cubes mesh generator.
pub struct MarchingCubes {
    /// Threshold for surface (typically 0.0 for signed distance).
    pub iso_level: f32,
}

impl MarchingCubes {
    pub fn new() -> Self {
        Self { iso_level: 0.0 }
    }

    /// Generate mesh from a 3D grid of voxels.
    ///
    /// The grid should be indexed as `grid[x][y][z]`.
    /// `origin` is the world position of grid[0][0][0].
    /// `cell_size` is the distance between grid points.
    pub fn generate(
        &self,
        grid: &[Vec<Vec<Voxel>>],
        origin: Point3<f32>,
        cell_size: f32,
    ) -> MarchingCubesMesh {
        let mut mesh = MarchingCubesMesh::new();

        let size_x = grid.len();
        if size_x < 2 {
            return mesh;
        }
        let size_y = grid[0].len();
        if size_y < 2 {
            return mesh;
        }
        let size_z = grid[0][0].len();
        if size_z < 2 {
            return mesh;
        }

        // Process each cell in the grid
        for x in 0..size_x - 1 {
            for y in 0..size_y - 1 {
                for z in 0..size_z - 1 {
                    self.process_cell(grid, x, y, z, origin, cell_size, &mut mesh);
                }
            }
        }

        // Compute normals from geometry
        self.compute_normals(&mut mesh);

        mesh
    }

    fn process_cell(
        &self,
        grid: &[Vec<Vec<Voxel>>],
        x: usize,
        y: usize,
        z: usize,
        origin: Point3<f32>,
        cell_size: f32,
        mesh: &mut MarchingCubesMesh,
    ) {
        // Get the 8 corner voxels of this cell
        let corners = [
            &grid[x][y][z],
            &grid[x + 1][y][z],
            &grid[x + 1][y][z + 1],
            &grid[x][y][z + 1],
            &grid[x][y + 1][z],
            &grid[x + 1][y + 1][z],
            &grid[x + 1][y + 1][z + 1],
            &grid[x][y + 1][z + 1],
        ];

        // Compute corner positions
        let positions = [
            Point3::new(
                origin.x + x as f32 * cell_size,
                origin.y + y as f32 * cell_size,
                origin.z + z as f32 * cell_size,
            ),
            Point3::new(
                origin.x + (x + 1) as f32 * cell_size,
                origin.y + y as f32 * cell_size,
                origin.z + z as f32 * cell_size,
            ),
            Point3::new(
                origin.x + (x + 1) as f32 * cell_size,
                origin.y + y as f32 * cell_size,
                origin.z + (z + 1) as f32 * cell_size,
            ),
            Point3::new(
                origin.x + x as f32 * cell_size,
                origin.y + y as f32 * cell_size,
                origin.z + (z + 1) as f32 * cell_size,
            ),
            Point3::new(
                origin.x + x as f32 * cell_size,
                origin.y + (y + 1) as f32 * cell_size,
                origin.z + z as f32 * cell_size,
            ),
            Point3::new(
                origin.x + (x + 1) as f32 * cell_size,
                origin.y + (y + 1) as f32 * cell_size,
                origin.z + z as f32 * cell_size,
            ),
            Point3::new(
                origin.x + (x + 1) as f32 * cell_size,
                origin.y + (y + 1) as f32 * cell_size,
                origin.z + (z + 1) as f32 * cell_size,
            ),
            Point3::new(
                origin.x + x as f32 * cell_size,
                origin.y + (y + 1) as f32 * cell_size,
                origin.z + (z + 1) as f32 * cell_size,
            ),
        ];

        // Compute cube index based on which corners are inside the surface
        let mut cube_index = 0u8;
        for (i, corner) in corners.iter().enumerate() {
            if corner.density > self.iso_level {
                cube_index |= 1 << i;
            }
        }

        // Skip if entirely inside or outside
        if cube_index == 0 || cube_index == 255 {
            return;
        }

        // Get edge flags from table
        let edge_flags = EDGE_TABLE[cube_index as usize];
        if edge_flags == 0 {
            return;
        }

        // Interpolate vertices on edges
        let mut edge_vertices = [Point3::origin(); 12];
        let mut edge_colors = [[0.0f32; 4]; 12];

        for i in 0..12 {
            if edge_flags & (1 << i) != 0 {
                let (v0, v1) = EDGE_CONNECTIONS[i];
                edge_vertices[i] = interpolate_vertex(
                    positions[v0],
                    positions[v1],
                    corners[v0].density,
                    corners[v1].density,
                    self.iso_level,
                );
                // Blend colors based on interpolation
                edge_colors[i] = blend_colors(
                    corners[v0].material.color(),
                    corners[v1].material.color(),
                    corners[v0].density,
                    corners[v1].density,
                    self.iso_level,
                );
            }
        }

        // Get triangles from table
        let triangles = &TRI_TABLE[cube_index as usize];
        let base_index = mesh.positions.len() as u32;

        let mut i = 0;
        while i < triangles.len() && triangles[i] != -1 {
            // Add three vertices for this triangle
            for j in 0..3 {
                let edge = triangles[i + j] as usize;
                mesh.positions.push(edge_vertices[edge]);
                mesh.colors.push(edge_colors[edge]);
                mesh.normals.push(Vector3::zeros()); // Will be computed later
                mesh.indices.push(base_index + (i + j) as u32);
            }
            i += 3;
        }
    }

    fn compute_normals(&self, mesh: &mut MarchingCubesMesh) {
        // Reset normals
        for normal in mesh.normals.iter_mut() {
            *normal = Vector3::zeros();
        }

        // Accumulate face normals to vertices
        for tri_idx in mesh.indices.chunks(3) {
            let i0 = tri_idx[0] as usize;
            let i1 = tri_idx[1] as usize;
            let i2 = tri_idx[2] as usize;

            let v0 = mesh.positions[i0];
            let v1 = mesh.positions[i1];
            let v2 = mesh.positions[i2];

            let edge1 = v1 - v0;
            let edge2 = v2 - v0;
            let face_normal = edge1.cross(&edge2);

            mesh.normals[i0] += face_normal;
            mesh.normals[i1] += face_normal;
            mesh.normals[i2] += face_normal;
        }

        // Normalize
        for normal in mesh.normals.iter_mut() {
            if normal.magnitude_squared() > 1e-10 {
                *normal = normal.normalize();
            } else {
                *normal = Vector3::new(0.0, 1.0, 0.0);
            }
        }
    }
}

impl Default for MarchingCubes {
    fn default() -> Self {
        Self::new()
    }
}

/// Interpolate vertex position along an edge based on density values.
fn interpolate_vertex(
    p0: Point3<f32>,
    p1: Point3<f32>,
    d0: f32,
    d1: f32,
    iso_level: f32,
) -> Point3<f32> {
    let t = if (d1 - d0).abs() > 1e-6 {
        (iso_level - d0) / (d1 - d0)
    } else {
        0.5
    };
    let t = t.clamp(0.0, 1.0);
    Point3::from(p0.coords.lerp(&p1.coords, t))
}

/// Blend two colors based on density interpolation.
fn blend_colors(c0: [f32; 4], c1: [f32; 4], d0: f32, d1: f32, iso_level: f32) -> [f32; 4] {
    let t = if (d1 - d0).abs() > 1e-6 {
        (iso_level - d0) / (d1 - d0)
    } else {
        0.5
    };
    let t = t.clamp(0.0, 1.0);
    [
        c0[0] + (c1[0] - c0[0]) * t,
        c0[1] + (c1[1] - c0[1]) * t,
        c0[2] + (c1[2] - c0[2]) * t,
        c0[3] + (c1[3] - c0[3]) * t,
    ]
}

