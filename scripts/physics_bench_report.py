#!/usr/bin/env python3
"""Summarize physics benchmark CSV outputs.

Reads CSV exports generated by the bench harness under target/physics_bench
and prints one compact row per run.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path
from typing import Any


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Summarize physics bench CSV outputs")
    parser.add_argument(
        "--input-dir",
        default="target/physics_bench",
        help="Directory containing bench CSV files",
    )
    parser.add_argument(
        "--tail-seconds",
        type=float,
        default=1.0,
        help="Tail window used for max speed summaries",
    )
    return parser.parse_args()


def parse_row(raw: dict[str, str]) -> dict[str, Any]:
    return {
        "scenario": raw["scenario"],
        "restitution": float(raw["restitution"]),
        "fixed_dt": float(raw["fixed_dt"]),
        "sim_time": float(raw["sim_time"]),
        "linear_speed": float(raw["linear_speed"]),
        "angular_speed": float(raw["angular_speed"]),
        "y": float(raw["y"]),
        "contact_count": int(raw["contact_count"]),
        "max_contact_depth": float(raw["max_contact_depth"]),
        "eff_restitution_avg": float(raw["eff_restitution_avg"]),
        "eff_restitution_max": float(raw["eff_restitution_max"]),
        "eff_restitution_closing": int(raw["eff_restitution_closing"]),
        "manifold_points": int(raw["manifold_points"]),
        "manifold_churn": int(raw["manifold_churn"]),
    }


def summarize(rows: list[dict[str, Any]], tail_seconds: float) -> dict[str, Any]:
    rows = sorted(rows, key=lambda r: r["sim_time"])
    last = rows[-1]
    max_time = last["sim_time"]
    tail_start = max(max_time - tail_seconds, 0.0)
    tail = [r for r in rows if r["sim_time"] >= tail_start]
    if not tail:
        tail = [last]

    tail_linear_max = max(r["linear_speed"] for r in tail)
    tail_angular_max = max(r["angular_speed"] for r in tail)

    return {
        "scenario": last["scenario"],
        "restitution": last["restitution"],
        "fixed_dt": last["fixed_dt"],
        "sim_duration": max_time,
        "final_y": last["y"],
        "tail_linear_max": tail_linear_max,
        "tail_angular_max": tail_angular_max,
        "eff_r_avg_peak": max(r["eff_restitution_avg"] for r in rows),
        "eff_r_max_peak": max(r["eff_restitution_max"] for r in rows),
        "closing_peak": max(r["eff_restitution_closing"] for r in rows),
        "churn_peak": max(r["manifold_churn"] for r in rows),
        "churn_avg": sum(r["manifold_churn"] for r in rows) / len(rows),
        "manifold_points_peak": max(r["manifold_points"] for r in rows),
        "contacts_final": last["contact_count"],
        "depth_final": last["max_contact_depth"],
    }


def fmt(summary: dict[str, Any]) -> list[str]:
    return [
        summary["scenario"],
        f"{summary['restitution']:.2f}",
        f"{summary['fixed_dt']:.6f}",
        f"{summary['sim_duration']:.2f}",
        f"{summary['tail_linear_max']:.5f}",
        f"{summary['tail_angular_max']:.5f}",
        f"{summary['eff_r_avg_peak']:.5f}",
        f"{summary['eff_r_max_peak']:.5f}",
        str(summary["closing_peak"]),
        str(summary["churn_peak"]),
        f"{summary['churn_avg']:.2f}",
        str(summary["manifold_points_peak"]),
        str(summary["contacts_final"]),
        f"{summary['depth_final']:.5f}",
        f"{summary['final_y']:.5f}",
    ]


def print_table(summaries: list[dict[str, Any]]) -> None:
    headers = [
        "scenario",
        "rest",
        "dt",
        "t_end",
        "tail_v",
        "tail_w",
        "eff_r_avg_pk",
        "eff_r_max_pk",
        "closing_pk",
        "churn_pk",
        "churn_avg",
        "m_pts_pk",
        "contacts_end",
        "depth_end",
        "y_end",
    ]
    rows = [fmt(s) for s in summaries]
    widths = [len(h) for h in headers]
    for row in rows:
        for i, cell in enumerate(row):
            widths[i] = max(widths[i], len(cell))

    def line(values: list[str]) -> str:
        return "  ".join(v.ljust(widths[i]) for i, v in enumerate(values))

    print(line(headers))
    print("  ".join("-" * w for w in widths))
    for row in rows:
        print(line(row))


def main() -> int:
    args = parse_args()
    input_dir = Path(args.input_dir)
    csv_files = sorted(input_dir.glob("*.csv"))
    if not csv_files:
        print(f"No CSV files found in {input_dir}")
        return 1

    summaries: list[dict[str, Any]] = []
    for csv_path in csv_files:
        with csv_path.open("r", encoding="utf-8", newline="") as f:
            reader = csv.DictReader(f)
            rows = [parse_row(row) for row in reader]
        if not rows:
            continue
        summary = summarize(rows, tail_seconds=args.tail_seconds)
        summary["file"] = csv_path.name
        summaries.append(summary)

    summaries.sort(key=lambda s: (s["scenario"], s["restitution"]))
    if not summaries:
        print(f"CSV files in {input_dir} were empty")
        return 1

    print_table(summaries)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
